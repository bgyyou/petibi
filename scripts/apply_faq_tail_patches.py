def main():
    n_files = 0
    n_changed = 0
    n_not_found = 0

    for personality, patches in PATCHES.items():
        fpath = ENCYCLOPEDIA_DIR / f"{personality.lower()}.json"
        if not fpath.exists():
            print(f"[WARN] {fpath} 不存在，跳过")
            continue
        data = json.loads(fpath.read_text(encoding="utf-8"))
        file_changed = 0
        missing_ids = []

        for e in data["entries"]:
            if e.get("category") != "faq":
                continue
            eid = e["id"]
            if eid not in patches:
                continue
            old_content = e["content"]
            new_content = patches[eid]
            if old_content != new_content:
                e["content"] = new_content
                file_changed += 1
                n_changed += 1

        if file_changed:
            fpath.write_text(
                json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            n_files += 1

        print(f"  [{personality}] 改 {file_changed} 条 FAQ")
        n_not_found += len(missing_ids)

    print()
    print(f"总计：{n_files} 个文件被修改，{n_changed} 条 FAQ 内容被改写。")


if __name__ == "__main__":
    main()