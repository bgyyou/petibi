    cats = ["code", "homework", "generate", "web", "roleplay"]
    out = {"categories": cats, "templates": {}}
    for mbti in [
        "INTJ", "INTP", "ENTJ", "ENTP",
        "INFJ", "INFP", "ENFJ", "ENFP",
        "ISTJ", "ISFJ", "ESTJ", "ESFJ",
        "ISTP", "ISFP", "ESTP", "ESFP",
    ]:
        per = REFUSALS[mbti]
        out["templates"][mbti] = {c: per[c] for c in cats}

    target = REPO_ROOT / "data" / "refusals.json"
    target.write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    total = sum(len(t) for per in out["templates"].values() for t in per.values())
    print(f"已写入 {target.relative_to(REPO_ROOT)}：{total} 条")


