def main():
    by_file = {}
    for (p, eid), content in OVERRIDES.items():
        by_file.setdefault(p, []).append((eid, content))

    total_updated = 0
    total_unknown = []

    for p, items in sorted(by_file.items()):
        fpath = ENCYCLOPEDIA_DIR / f"{p}.json"
        if not fpath.exists():
            print(f"FAIL: 文件不存在 {fpath}", file=sys.stderr)
            return 1
        data = json.loads(fpath.read_text(encoding="utf-8"))
        id_map = {e["id"]: e for e in data.get("entries", [])}

        n = 0
        for eid, new_content in items:
            if eid not in id_map:
                total_unknown.append((p, eid))
                continue
            entry = id_map[eid]
            cat = entry["category"]
            if cat in LEN_RULES:
                lo, hi = LEN_RULES[cat]
                if not (lo <= len(new_content) <= hi):
                    print(f"WARN  {p}/{eid} [{cat}]: 字数 {len(new_content)} 不在 [{lo},{hi}]")
            elif cat in SOFT_LIMITS:
                lo, hi = SOFT_LIMITS[cat]
                if not (lo <= len(new_content) <= hi):
                    print(f"WARN  {p}/{eid} [{cat}]: 字数 {len(new_content)} 不在 [{lo},{hi}]")
            entry["content"] = new_content
            n += 1

        fpath.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"  {p}: 改写 {n} 条")
        total_updated += n

    if total_unknown:
        print("\nFAIL  未知 entry id:")
        for p, eid in total_unknown:
            print(f"  - {p}/{eid}")
        return 1

    print(f"\n总计改写 {total_updated} 条。")
    return 0


if __name__ == "__main__":
    sys.exit(main())