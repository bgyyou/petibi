def apply_substitutions_to_entry(text, all_other_texts):
    """迭代应用替换，直到与所有其他条目无重叠。"""
    keys_sorted = sorted(SUBSTITUTIONS.keys(), key=len, reverse=True)
    out = text
    for _ in range(50):
        changed = False
        for orig in keys_sorted:
            if orig not in out:
                continue
            cands = SUBSTITUTIONS[orig]
            for cand in cands:
                # 检查 cand 不在 out 里
                if cand in out:
                    continue
                # 检查 cand 不与其他条目产生新的 ≥10 字重叠
                introduces_overlap = False
                for partner_text in all_other_texts:
                    if len(cand) >= 10 and cand in partner_text:
                        cs = lcs_pairs(out.replace(orig, cand, 1), partner_text)
                        if cs:
                            introduces_overlap = True
                            break
                if introduces_overlap:
                    continue
                out = out.replace(orig, cand, 1)
                changed = True
                break
            if changed:
                break
        if not changed:
            break
    return out


def run_scan(out_path):
    env = os.environ.copy()
    env["PYTHONIOENCODING"] = "utf-8"
    env["PATH"] = "/usr/bin:/bin:" + env.get("PATH", "")
    res = subprocess.run([
        sys.executable, str(SCRIPTS_DIR / "scan_entry_overlap.py"),
        "--cross", "--json", str(out_path),
    ], cwd=REPO_ROOT, env=env, capture_output=True, text=True)
    return Path(out_path).exists()


def main():
    scan_path = TMP_DIR / "m4-cross-now.json"
    if not run_scan(scan_path):
        print("scan failed")
        return 1
    data = json.loads(scan_path.read_text(encoding="utf-8"))

    # 加载所有受影响条目的内容
    affected_keys = set()
    for item in data["cross_personality"]:
        for e in item["entries"]:
            affected_keys.add((e["personality"], e["id"]))

    # 加载百科库全部内容（避免跨未受影响条目引入新重叠）
    all_entries = {}  # key: (p, eid) -> content
    for fn in ENCYCLOPEDIA_DIR.glob("*.json"):
        if fn.name == "index.json" or fn.name == "scenarios.md":
            continue
        d = json.loads(fn.read_text(encoding="utf-8"))
        p = d["personality"]
        for e in d["entries"]:
            all_entries[(p, e["id"])] = e["content"]

    # 按对端条目数迭代
    for it in range(8):
        if not data["cross_personality"]:
            print(f"iter {it}: 0 个跨人格重叠")
            break

        # 收集每条文本涉及的 partners（避免做不必要的工作）
        partner_map = {}
        for item in data["cross_personality"]:
            ents = item["entries"]
            for i in range(len(ents)):
                for j in range(len(ents)):
                    if i != j:
                        key = (ents[i]["personality"], ents[i]["id"])
                        partner_map.setdefault(key, set()).add(
                            (ents[j]["personality"], ents[j]["id"])
                        )

        changed = 0
        for (p, eid), partners in partner_map.items():
            e, data_file = load_entry(p, eid)
            if e is None:
                continue
            cur = e["content"]
            # 收集所有 partner 的内容 + 其他受影响条目的内容
            other_texts = []
            for (pp, ee) in partners:
                pt = all_entries.get((pp, ee))
                if pt:
                    other_texts.append(pt)
            # 应用替换直到所有重叠消除
            new = apply_substitutions_to_entry(cur, other_texts)
            if new != cur:
                # 检查长度
                cat = e["category"]
                if cat == "faq":
                    if 120 <= len(new) <= 200:
                        e["content"] = new
                        all_entries[(p, eid)] = new
                        save_entry(p, data_file)
                        changed += 1
                elif cat == "trait":
                    if 80 <= len(new) <= 150:
                        e["content"] = new
                        all_entries[(p, eid)] = new
                        save_entry(p, data_file)
                        changed += 1
                else:
                    if 50 <= len(new) <= 200:
                        e["content"] = new
                        all_entries[(p, eid)] = new
                        save_entry(p, data_file)
                        changed += 1

        print(f"iter {it}: 修改 {changed} 条")
        if changed == 0:
            break
        # 重新扫描
        scan_path = TMP_DIR / f"m4-cross-iter{it+1}.json"
        if not run_scan(scan_path):
            break
        data = json.loads(scan_path.read_text(encoding="utf-8"))
        print(f"  剩余: {len(data['cross_personality'])}")

    return 0


if __name__ == "__main__":
    sys.exit(main())