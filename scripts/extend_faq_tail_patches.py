def main():
    n_changed = 0
    for eid, new_content in EXTENDED.items():
        personality = eid.split("-")[0]
        fpath = ENCYCLOPEDIA_DIR / f"{personality.lower()}.json"
        data = json.loads(fpath.read_text(encoding="utf-8"))
        for e in data["entries"]:
            if e["id"] == eid:
                if e["content"] != new_content:
                    e["content"] = new_content
                    n_changed += 1
                break
        fpath.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"扩展了 {n_changed} 条 FAQ 的尾巴（补到 ≥120 字）")


