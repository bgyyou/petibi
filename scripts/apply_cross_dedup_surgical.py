def lcs_pairs(a, b, min_len=10):
    """Return list of all common substrings of length >= min_len (maximal)."""
    la, lb = len(a), len(b)
    if la < min_len or lb < min_len:
        return []
    dp = [[0] * (lb + 1) for _ in range(la + 1)]
    for i in range(1, la + 1):
        for j in range(1, lb + 1):
            if a[i - 1] == b[j - 1]:
                dp[i][j] = dp[i - 1][j - 1] + 1
    out = []
    for i in range(1, la + 1):
        for j in range(1, lb + 1):
            L = dp[i][j]
            if L < min_len:
                continue
            if i < la and j < lb and dp[i + 1][j + 1] == L + 1:
                continue
            out.append(a[i - L:i])
    return out


def find_replacement(text, partner_text, max_depth=3):
    """Try to apply REPLACEMENTS iteratively to break overlap."""
    # Use longest-first matching
    keys_sorted = sorted(REPLACEMENTS, key=lambda x: -len(x[0]))
    new = text
    for _ in range(max_depth):
        changed = False
        for orig, cands in keys_sorted:
            if orig not in new:
                continue
            for cand in cands:
                if cand in new or cand in partner_text:
                    continue
                test = new.replace(orig, cand, 1)
                if test == new:
                    continue
                new = test
                changed = True
                break
            if changed:
                break
        if not changed:
            break
    return new


def run_scan(out_path):
    env = {"PYTHONIOENCODING": "utf-8", "PATH": "/usr/bin:/bin"}
    res = subprocess.run([
        sys.executable, str(SCRIPTS_DIR / "scan_entry_overlap.py"),
        "--cross", "--json", str(out_path),
    ], cwd=REPO_ROOT, env=env, capture_output=True, text=True)
    return Path(out_path).exists()


def load_entry(p, eid):
    fpath = ENCYCLOPEDIA_DIR / f"{p.lower()}.json"
    if not fpath.exists():
        return None, None
    data = json.loads(fpath.read_text(encoding="utf-8"))
    for e in data["entries"]:
        if e["id"] == eid:
            return e, data
    return None, None


def save_entry(p, data):
    fpath = ENCYCLOPEDIA_DIR / f"{p.lower()}.json"
    fpath.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def main():
    scan_path = Path("/tmp/m4-cross-current.json")
    run_scan(scan_path)
    data = json.loads(scan_path.read_text(encoding="utf-8"))

    max_iter = 30
    for it in range(max_iter):
        if not data["cross_personality"]:
            print(f"iter {it}: 0 个跨人格重叠")
            break
        # 收集所有 (personality, entry_id) 涉及的条目
        affected_pairs = []
        for item in data["cross_personality"]:
            ents = item["entries"]
            if len(ents) >= 2:
                keys = sorted([(e["personality"], e["id"]) for e in ents])
                affected_pairs.append((tuple(keys), item["fragment"]))

        # 统计每条涉及的 partners
        partner_map = {}
        for keys, frag in affected_pairs:
            for i in range(len(keys)):
                for j in range(len(keys)):
                    if i != j:
                        partner_map.setdefault(keys[i], []).append((keys[j], frag))

        changed = 0
        # 选较短的条目作为改写目标
        sizes = {}
        for p, eid in partner_map:
            e, _ = load_entry(p, eid)
            if e:
                sizes[(p, eid)] = len(e["content"])

        for (p, eid), partners in partner_map.items():
            e, data_file = load_entry(p, eid)
            if e is None:
                continue
            cur = e["content"]
            for (p2, e2), shared_frag in partners:
                if sizes.get((p, eid), 0) >= sizes.get((p2, e2), 999):
                    continue
                e2_entry, _ = load_entry(p2, e2)
                if e2_entry is None:
                    continue
                partner_text = e2_entry["content"]
                # 应用替换直到无重叠
                for _ in range(3):
                    cs = lcs_pairs(cur, partner_text)
                    if not cs:
                        break
                    # 找包含 cs 中最长片段的短语
                    longest = max(cs, key=len)
                    new = find_replacement(cur, partner_text, max_depth=2)
                    if new == cur:
                        # 没找到匹配，尝试在 cur 中找一段包含 longest 的最长已知 key
                        for orig, cands in REPLACEMENTS:
                            if orig in cur and longest in orig:
                                for cand in cands:
                                    if cand not in cur and cand not in partner_text:
                                        cur = cur.replace(orig, cand, 1)
                                        new = cur
                                        break
                                if new != cur:
                                    break
                    cur = new
                    if cur == e["content"]:
                        break

            if cur != e["content"]:
                e["content"] = cur
                save_entry(p, data_file)
                sizes[(p, eid)] = len(cur)
                changed += 1

        print(f"iter {it}: 修改 {changed} 条")
        if changed == 0:
            # 最后一次扫描
            scan_path2 = Path(f"/tmp/m4-cross-iter{it+1}.json")
            run_scan(scan_path2)
            data2 = json.loads(scan_path2.read_text(encoding="utf-8"))
            print(f"剩余跨人格片段：{len(data2['cross_personality'])}")
            if data2["cross_personality"]:
                # 还有剩余，强制再扫一次
                data = data2
                continue
            break
        # 重新扫描
        run_scan(scan_path)
        data = json.loads(scan_path.read_text(encoding="utf-8"))
        print(f"剩余：{len(data['cross_personality'])}")

    return 0


if __name__ == "__main__":
    sys.exit(main())