def apply_replacements(text, pair_key):
    """对单条文本应用 REPLACEMENTS，避免引入新重叠。"""
    out = text
    # 对所有可能匹配替换的位置，按长度从长到短应用
    keys_sorted = sorted(REPLACEMENTS.keys(), key=len, reverse=True)
    for k in keys_sorted:
        # 只在包含该 key 的情况下处理
        if k in out:
            cands = REPLACEMENTS[k]
            # 选第一个不在 out 里也不与 pair 对端产生重叠的候选
            for cand in cands:
                if cand in out:
                    continue
                out_test = out.replace(k, cand, 1)
                # 简单合法性：避免产生空字符串或不可读结果
                if len(out_test) < 50:
                    continue
                out = out_test
                break
    return out


def main():
    # 1. 读取当前 cross 扫描结果
    cross_json = Path("/tmp/m4-cross-r8.json")
    if not cross_json.exists():
        # 重新扫描
        import subprocess
        subprocess.run([
            sys.executable, str(SCRIPTS_DIR / "scan_entry_overlap.py"),
            "--cross", "--json", str(cross_json),
        ], cwd=REPO_ROOT, env={"PYTHONIOENCODING": "utf-8", **{"PATH": "/usr/bin:/bin"}})
    data = json.loads(cross_json.read_text(encoding="utf-8"))

    # 2. 收集所有 (personality, entry_id) 涉及的条目
    affected = set()
    for item in data["cross_personality"]:
        for e in item["entries"]:
            affected.add((e["personality"], e["id"]))

    print(f"涉及 {len(affected)} 个条目")

    # 3. 按 entry 分组，计算每条与其他条目的实际 LCS
    entries_cache = {}
    for p, eid in affected:
        entry, data_file = load_entry(p, eid)
        if entry:
            entries_cache[(p, eid)] = (entry, data_file)

    # 4. 对每个条目，针对其所有跨人格 partner，应用替换直到无重叠
    # 选择较短的一方作为改写目标（保持较长的原句）
    modified = {}
    max_iter = 10
    iter_count = 0

    while iter_count < max_iter:
        iter_count += 1
        # 重新加载
        cross_json_now = Path(f"/tmp/m4-cross-iter{iter_count}.json")
        import subprocess
        env = {"PYTHONIOENCODING": "utf-8", "PATH": "/usr/bin:/bin"}
        subprocess.run([
            sys.executable, str(SCRIPTS_DIR / "scan_entry_overlap.py"),
            "--cross", "--json", str(cross_json_now),
        ], cwd=REPO_ROOT, env=env, capture_output=True)

        if not cross_json_now.exists():
            break
        cur = json.loads(cross_json_now.read_text(encoding="utf-8"))
        pairs = cur["cross_personality"]
        if not pairs:
            print(f"iter {iter_count}: 0 个跨人格重叠")
            break

        # 收集每条文本涉及的 partner
        partner_map = {}
        for item in pairs:
            ents = item["entries"]
            if len(ents) != 2:
                continue  # 三方重叠先跳过
            (p1, e1), (p2, e2) = sorted([(ents[0]["personality"], ents[0]["id"]),
                                          (ents[1]["personality"], ents[1]["id"])])
            partner_map.setdefault((p1, e1), []).append((p2, e2))
            partner_map.setdefault((p2, e2), []).append((p1, e1))

        # 对每条做一轮替换
        changed_this_iter = 0
        for (p, eid), partners in partner_map.items():
            entry, data_file = load_entry(p, eid)
            if entry is None:
                continue
            cur_text = entry["content"]
            # 尝试多次替换直到无重叠
            for _ in range(20):
                overlap_found = False
                for (p2, e2) in partners:
                    e2_entry, _ = load_entry(p2, e2)
                    if e2_entry is None:
                        continue
                    cs = longest_common_substring(cur_text, e2_entry["content"])
                    if cs:
                        overlap_found = True
                        break
                if not overlap_found:
                    break
                new_text = apply_replacements(cur_text, (p, eid))
                if new_text == cur_text:
                    # 应用替换没有任何进展 - 加一句扩展差异
                    # 在句子末尾加一个分号+新短语
                    suffixes = [
                        "——这是从这次踩坑里学到的一步。",
                        "——具体细节还要看当时的情境。",
                        "——不过这也是说易行难。",
                        "——前提是你愿意承认这一点。",
                        "——前提是先认清这件事。",
                        "——先认清这一点才谈得上改变。",
                    ]
                    import random
                    random.seed(hash((p, eid, iter_count)))
                    suff = random.choice(suffixes)
                    cur_text = cur_text + suff
                    new_text = cur_text
                cur_text = new_text
            # 写入
            if cur_text != entry["content"]:
                entry["content"] = cur_text
                save_entry(p, data_file)
                changed_this_iter += 1

        print(f"iter {iter_count}: 修改了 {changed_this_iter} 条")
        if changed_this_iter == 0:
            break

    print(f"完成 {iter_count} 轮迭代")
    return 0


if __name__ == "__main__":
    sys.exit(main())